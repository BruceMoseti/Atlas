#!/usr/bin/env python3
"""Render the figures in README.md from the committed experiment output.

The charts are generated by parsing results/*.txt rather than from numbers typed
into this file, so a figure cannot drift away from the run it claims to show. If
the experiments are re-run, re-running this script is what updates the images.

    make experiments      # regenerate results/*.txt
    make figures          # regenerate docs/images/*.png from them
"""

from __future__ import annotations

import pathlib
import re
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
IMAGES = ROOT / "docs" / "images"

# A muted, print-safe palette. Distinguishable in greyscale, which matters because
# people do print these things.
COLORS = {
    "round-robin": "#8c8c8c",
    "least-loaded": "#2f6f9f",
    "best-fit": "#c4642a",
    "none": "#c4642a",
    "queue<=500": "#2f6f9f",
}

plt.rcParams.update(
    {
        "font.family": "DejaVu Sans",
        "font.size": 9,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "axes.grid": True,
        "axes.axisbelow": True,
        "grid.color": "#e6e6e6",
        "grid.linewidth": 0.8,
        "figure.dpi": 200,
    }
)


def parse_duration(text: str) -> float:
    """Convert the simulator's compact duration format into seconds."""
    m = re.fullmatch(r"([\d.]+)(ms|s|m|h)", text.strip())
    if not m:
        raise ValueError(f"unrecognized duration {text!r}")
    value, unit = float(m.group(1)), m.group(2)
    return value * {"ms": 1e-3, "s": 1.0, "m": 60.0, "h": 3600.0}[unit]


def parse_table(path: pathlib.Path, header_starts_with: str) -> list[list[str]]:
    """Pull one whitespace-aligned table out of a report, as rows of cells."""
    rows: list[list[str]] = []
    in_table = False
    for line in path.read_text().splitlines():
        if line.startswith(header_starts_with):
            in_table = True
            continue
        if not in_table:
            continue
        if not line.strip():
            break
        rows.append(re.split(r"\s{2,}", line.strip()))
    if not rows:
        raise SystemExit(f"no table starting with {header_starts_with!r} in {path}")
    return rows


def fragmentation_chart() -> None:
    """Mean wait by policy on two fleets of identical total capacity."""
    rows = parse_table(RESULTS / "fragmentation.txt", "FLEET")
    data: dict[str, dict[str, float]] = {}
    stranded: dict[str, dict[str, float]] = {}
    for fleet, policy, mean_wait, _p99, _cpu, _mem, strand_cpu, _strand_mem in rows:
        data.setdefault(fleet, {})[policy] = parse_duration(mean_wait)
        stranded.setdefault(fleet, {})[policy] = float(strand_cpu.rstrip("%"))

    policies = ["round-robin", "least-loaded", "best-fit"]
    fleets = ["uniform", "heterogeneous"]

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(9.0, 3.4))
    width = 0.26
    positions = range(len(fleets))

    for i, policy in enumerate(policies):
        offset = (i - 1) * width
        values = [data[f][policy] for f in fleets]
        bars = ax1.bar(
            [p + offset for p in positions], values, width,
            label=policy, color=COLORS[policy], edgecolor="white", linewidth=0.5,
        )
        ax1.bar_label(bars, fmt="%.1fs", padding=2, fontsize=8)

        values = [stranded[f][policy] for f in fleets]
        bars = ax2.bar(
            [p + offset for p in positions], values, width,
            label=policy, color=COLORS[policy], edgecolor="white", linewidth=0.5,
        )
        ax2.bar_label(bars, fmt="%.0f%%", padding=2, fontsize=8)

    for ax, title, ylabel in (
        (ax1, "Mean queue wait (lower is better)", "seconds"),
        (ax2, "Stranded CPU while jobs waited", "% of fleet idle"),
    ):
        ax.set_xticks(list(positions))
        ax.set_xticklabels(["uniform fleet", "heterogeneous fleet"])
        ax.set_title(title, fontsize=10, pad=8)
        ax.set_ylabel(ylabel)
        ax.margins(y=0.18)

    ax1.legend(frameon=False, fontsize=8, loc="upper left")
    fig.suptitle(
        "Identical total capacity (384 cores, 928 GiB, 20 machines) — only machine shape differs",
        fontsize=9, y=1.01, color="#555555",
    )
    fig.tight_layout()
    save(fig, "fragmentation.png")


def overload_chart() -> None:
    """Tail latency versus arrival rate, with and without admission control."""
    rows = parse_table(RESULTS / "overload.txt", "ARRIVAL/S")
    series: dict[str, list[tuple[float, float]]] = {}
    queues: dict[str, list[tuple[float, float]]] = {}
    for rate, admission, _acc, _rej, peak, _mean, p99, _cpu in rows:
        series.setdefault(admission, []).append((float(rate), parse_duration(p99)))
        queues.setdefault(admission, []).append((float(rate), float(peak)))

    labels = {"none": "unbounded queue", "queue<=500": "admission control (queue \u2264 500)"}

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(9.0, 3.4))
    for admission, points in series.items():
        points.sort()
        xs = [p[0] for p in points]
        ys = [p[1] for p in points]
        ax1.plot(xs, ys, marker="o", markersize=4, linewidth=1.8,
                 color=COLORS[admission], label=labels[admission])
    for admission, points in queues.items():
        points.sort()
        xs = [p[0] for p in points]
        ys = [p[1] for p in points]
        ax2.plot(xs, ys, marker="o", markersize=4, linewidth=1.8,
                 color=COLORS[admission], label=labels[admission])

    ax1.set_title("p99 queue wait", fontsize=10, pad=8)
    ax1.set_ylabel("seconds")
    # symlog rather than log: below capacity the p99 wait is genuinely 0, and a
    # plain log axis would silently drop those points and make the line look
    # like it starts at 16 jobs/sec.
    ax1.set_yscale("symlog", linthresh=1)
    ax1.set_ylim(bottom=0)
    ax2.set_title("Peak queue depth", fontsize=10, pad=8)
    ax2.set_ylabel("jobs waiting (log scale)")
    ax2.set_yscale("log")

    for ax in (ax1, ax2):
        ax.set_xscale("log", base=2)
        ax.set_xlabel("arrival rate (jobs/sec)")
        ax.set_xticks([8, 16, 32, 64, 128])
        ax.get_xaxis().set_major_formatter(matplotlib.ticker.ScalarFormatter())
        # Capacity is ~16 jobs/sec; everything right of this line is overload.
        ax.axvline(16, color="#bbbbbb", linestyle="--", linewidth=1)
        # Axes-fraction y keeps the label clear of the data on both the symlog
        # and log panels, which have very different ranges.
        ax.text(17.5, 0.08, "capacity", transform=ax.get_xaxis_transform(),
                fontsize=7.5, color="#999999", va="bottom", rotation=90)

    ax1.legend(frameon=False, fontsize=8, loc="upper left")
    fig.suptitle(
        "20 workers, 2-core jobs — backpressure converts an invisible failure into a visible one",
        fontsize=9, y=1.01, color="#555555",
    )
    fig.tight_layout()
    save(fig, "overload.png")


def decision_cost_chart() -> None:
    """Placement decision cost as the fleet grows."""
    rows = parse_table(RESULTS / "scale.txt", "WORKERS")
    series: dict[str, list[tuple[int, float]]] = {}
    for workers, scenario, policy, mean, _p50, _p99, _dps in rows:
        if scenario != "busy, small job":
            continue
        series.setdefault(policy, []).append((int(workers), parse_duration_ns(mean)))

    fig, ax = plt.subplots(figsize=(5.2, 3.4))
    for policy in ["round-robin", "least-loaded", "best-fit"]:
        points = sorted(series[policy])
        ax.plot([p[0] for p in points], [p[1] for p in points],
                marker="o", markersize=4, linewidth=1.8,
                color=COLORS[policy], label=policy)

    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("workers in the fleet")
    ax.set_ylabel("nanoseconds per decision")
    ax.set_xticks([10, 100, 1000, 10000])
    ax.get_xaxis().set_major_formatter(matplotlib.ticker.ScalarFormatter())
    ax.set_title("Placement decision cost, 80% occupancy", fontsize=10, pad=8)
    ax.legend(frameon=False, fontsize=8, loc="upper left")

    # The shape is the point: slope 1 on a log-log plot is linear in fleet size.
    ax.annotate("linear in fleet size:\nevery worker is scored",
                xy=(2600, 5200), xytext=(150, 9000), fontsize=8, color="#7a4418",
                arrowprops=dict(arrowstyle="->", color="#b0b0b0", linewidth=0.9))
    ax.annotate("flat: stops at the first worker that fits",
                xy=(900, 36), xytext=(130, 90), fontsize=8, color="#666666",
                arrowprops=dict(arrowstyle="->", color="#b0b0b0", linewidth=0.9))
    fig.tight_layout()
    save(fig, "decision-cost.png")


def parse_duration_ns(text: str) -> float:
    """Parse the Go duration strings the scale benchmark emits, into nanoseconds."""
    m = re.fullmatch(r"([\d.]+)(ns|\u00b5s|us|ms|s)", text.strip())
    if not m:
        raise ValueError(f"unrecognized duration {text!r}")
    value, unit = float(m.group(1)), m.group(2)
    return value * {"ns": 1.0, "\u00b5s": 1e3, "us": 1e3, "ms": 1e6, "s": 1e9}[unit]


def save(fig, name: str) -> None:
    # PNG rather than SVG: it renders identically everywhere a README is read,
    # including link previews and offline markdown viewers.
    IMAGES.mkdir(parents=True, exist_ok=True)
    path = IMAGES / name
    fig.savefig(path, format="png", bbox_inches="tight", transparent=False,
                facecolor="white")
    plt.close(fig)
    print(f"wrote {path.relative_to(ROOT)}")


def main() -> int:
    missing = [f for f in ("fragmentation.txt", "overload.txt", "scale.txt")
               if not (RESULTS / f).exists()]
    if missing:
        print(f"missing results: {', '.join(missing)}. Run `make experiments` first.",
              file=sys.stderr)
        return 1

    fragmentation_chart()
    overload_chart()
    decision_cost_chart()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
